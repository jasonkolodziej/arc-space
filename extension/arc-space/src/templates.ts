export function workspaceFile(id: string, hasVault: boolean, vaultPath?: string, forNode = false): string {
  if (forNode) hasVault = false;
  const folders = [
    { name: 'home · code & envs (backed up · 100 GB)', path: `/home/${id}/projects` },
    { name: 'work · job I/O & data (no backup · 30-day purge)', path: `/work/${id}` },
    ...(hasVault ? [{ name: 'vault · archive (backed up · 1 TB)', path: vaultPath ?? `/vault/research/${id}` }] : []),
  ];
  const settings = workspaceSettings(id);
  const body = {
    folders,
    settings: { ...settings, 'arc.appliedTemplate': { version: WS_TEMPLATE_VERSION, values: settings } },
    extensions: { recommendations: ['ms-python.python', 'ms-toolsai.jupyter', 'timonwong.shellcheck'] },
  };
  return `// Generated by the Arc HPC extension (${forNode ? 'compute-node' : 'login-node'} workspace). Edit freely: "Arc: Review Workspace Settings"
// merges future template changes without overwriting your edits.${forNode ? `
// No vault folder here: /vault is mounted on the login nodes only. Vault actions run on the login node.` : ''}
${JSON.stringify(body, null, 2)}
`;
}

// ─────────────── SSH ───────────────

export const SSH_BEGIN = '# >>> arc-slurm >>>';
export const SSH_END = '# <<< arc-slurm <<<';
export const MANAGED_CONF = '~/.ssh/arc-slurm.conf';
export const PROXY_SCRIPT = '~/.ssh/arc-slurm-proxy.sh';

/** The only lines written into your own ssh config: an Include at the very top. */
export const includeBlock = () =>
  `${SSH_BEGIN}\n# Managed by the Arc HPC VS Code extension (Arc: Configure SSH).\nInclude ${MANAGED_CONF}\n${SSH_END}\n`;

/** Return `text` with exactly one managed Include block, placed at the very top. Idempotent. */
export function withIncludeBlock(text: string): string {
  const esc = (x: string) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const without = text.replace(new RegExp(`${esc(SSH_BEGIN)}[\\s\\S]*?${esc(SSH_END)}\\n*`, 'g'), '');
  return includeBlock() + (without ? '\n' + without : '');
}

export function managedConf(o: { id: string; login: string; node: string; identityFile?: string }): string {
  const key = o.identityFile
    ? `    IdentityFile ${o.identityFile}\n    IdentitiesOnly yes\n`
    : '';
  const agent = `    AddKeysToAgent yes\n    UseKeychain yes\n`;
  return `# Managed by the Arc HPC VS Code extension — regenerated by "Arc: Configure SSH".
# Local edits are overwritten; override options in your own ~/.ssh/config instead.

# Global (before any Host): lets UseKeychain (macOS-only) parse on every OpenSSH build.
IgnoreUnknown UseKeychain

# Hop 1: login node. One DUO sign-in opens the master socket; everything else reuses it.
Host ${o.login}
    HostName arc.utsa.edu
    Port 22
    User ${o.id}
    ControlMaster auto
    ControlPath ~/.ssh/cm-%C
    ControlPersist 10h
    ServerAliveInterval 60
    ServerAliveCountMax 5
    ForwardAgent no
${agent}${key}
# Hop 2: the compute node running your holder job (resolved at connect time).
# Host keys change per node and the hop is inside the authenticated login connection.
Host ${o.node}
    User ${o.id}
    ProxyCommand ${PROXY_SCRIPT}
    StrictHostKeyChecking no
    UserKnownHostsFile /dev/null
    LogLevel ERROR
    ServerAliveInterval 60
    ServerAliveCountMax 5
${agent}${key}
# Return to global scope so nothing that follows the Include is captured by the blocks above.
Host *
`;
}

export function proxyScript(login: string, holdJob: string, mode: 'forward' | 'relay' = 'forward'): string {
  return `#!/bin/sh
# Managed by the Arc HPC VS Code extension — ProxyCommand for the compute-node host.
# Finds the node running your holder job, then opens a byte stream to its sshd through
# the multiplexed login connection (no second DUO prompt).
#   forward: ssh -W (needs port forwarding allowed on the login node)
#   relay:   a bash /dev/tcp relay run on the login node (works when forwarding is prohibited)
#
# IMPORTANT: stdin/stdout of this script ARE the SSH connection. Anything that reads stdin
# (hence "ssh -n" for the lookup) or writes stdout before the final exec corrupts the handshake.
# Diagnostics therefore go to stderr and to ~/.ssh/arc-slurm-proxy.log.
JOB_NAME="\${ARC_HOLD_JOB:-${holdJob}}"
MODE="\${ARC_PROXY_MODE:-${mode}}"
LOG="\${HOME}/.ssh/arc-slurm-proxy.log"
log() { printf '%s [%s] %s\\n' "$(date '+%Y-%m-%dT%H:%M:%S')" "$$" "$*" >> "$LOG" 2>/dev/null; }
if [ -f "$LOG" ] && [ "$(wc -l < "$LOG")" -gt 400 ]; then tail -n 200 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"; fi

log "start job=$JOB_NAME mode=$MODE"
err=$(mktemp "\${TMPDIR:-/tmp}/arcproxy.XXXXXX")
node=$(ssh -n -o BatchMode=yes ${login} "squeue -u \\$USER --name=$JOB_NAME --states=RUNNING --noheader --format=%N" 2>"$err" \\
        | head -n1 | tr -d '[:space:]')
lookup_err=$(head -c 300 "$err" | tr '\\n' ' '); rm -f "$err"
if [ -z "$node" ]; then
  log "FAIL lookup: no RUNNING '$JOB_NAME' job; ssh said: $lookup_err"
  echo "arc: no RUNNING '$JOB_NAME' job, or the '${login}' master connection is down ($lookup_err). Use 'Arc: Sign In' / 'Arc: Allocate Compute Node'." >&2
  exit 1
fi
case "$node" in
  *\\[*) log "FAIL multi-node $node"; echo "arc: holder job spans multiple nodes ($node); use a 1-node job." >&2; exit 1 ;;
esac
log "node=$node → connecting ($MODE)"
if [ "$MODE" = relay ]; then
  exec ssh -o BatchMode=yes ${login} "bash -c 'exec 3<>/dev/tcp/$node/22; cat <&3 & exec cat >&3'"
fi
exec ssh -W "$node:22" ${login}
`;
}
