/*
 * Lmod modules (https://hpcsupport.utsa.edu/foswiki/bin/view/WebDocumentation/ModuleEnvironments).
 *
 * One Lmod collection (arc.moduleCollection, default "vscode") is the source of truth. The Modules
 * view edits it with module load/unload/swap + `module save`, and three small files on Arc make
 * VS Code follow it:
 *   ~/.arc/modules/load.sh      `module restore <collection>`, quietly (sourced by the two below)
 *   ~/.arc/modules/terminal.rc  bash --rcfile for VS Code terminals: ~/.bashrc, then load.sh
 *   ~/.arc/modules/vscode.env   env vars the collection changes (python.envFile → run/debug, tests, Jupyter)
 * Tasks get load.sh via BASH_ENV. Batch scripts can `module restore <collection>` or get explicit lines.
 */
import * as vscode from 'vscode';
import { cfg, runRemote, q, utsaId, onArc, arcTerminal, NotConfigured } from './transport';
import { ensureSignedIn } from './setup';
import { showReport } from './docs';
import { Item } from './views';

export const MOD_DIR = '.arc/modules';
export const TERMINAL_PROFILE = 'bash · Arc modules';
const DOCS = 'https://hpcsupport.utsa.edu/foswiki/bin/view/WebDocumentation/ModuleEnvironments';

export function collection(): string {
  const c = cfg().get<string>('moduleCollection', 'vscode').trim();
  if (!/^[\w.-]+$/.test(c)) throw new Error(`arc.moduleCollection "${c}" must be letters, digits, . _ -`);
  return c;
}

// Non-login `bash -c` over ssh has no `module` function yet.
const INIT = 'type module >/dev/null 2>&1 || . /etc/profile.d/lmod.sh >/dev/null 2>&1 || . /etc/profile >/dev/null 2>&1; ' +
  'type module >/dev/null 2>&1 || { echo "The module command (Lmod) is not available on this host." >&2; exit 3; }; ';
const lmod = (script: string) => runRemote(INIT + script, { timeoutMs: 120_000 });

/** Start from the saved collection if there is one, else from the system defaults /etc/profile loaded. */
const RESTORE = (c: string) =>
  `if module -t savelist 2>&1 | grep -qx ${q(c)}; then module --quiet restore ${q(c)} >/dev/null 2>&1; saved=1; else saved=0; fi; `;

const LMOD_ERROR = /Lmod has detected the following error|The following module\(s\) are unknown|Unable to find|cannot be loaded/i;
const clean = (s: string) => s.replace(/\s*\([^)]*\)\s*$/, '').trim();
const lines = (s: string) => s.split('\n').map(l => l.trim()).filter(Boolean);

export interface ModState { saved: boolean; loaded: string[]; }

export async function getState(): Promise<ModState> {
  if (!utsaId()) throw new NotConfigured();
  const out = await lmod(`${RESTORE(collection())} echo "@saved=$saved"; module -t list 2>&1`);
  const saved = out.includes('@saved=1');
  const loaded = lines(out).filter(l => !l.startsWith('@') && !/^No modules loaded/i.test(l) && !l.endsWith(':')).map(clean);
  return { saved, loaded };
}

// ─────────────── files on Arc ───────────────

function loadSh(c: string) {
  return `# Managed by the Arc HPC VS Code extension (Modules view) — restores the Lmod collection "${c}".
# Sourced by VS Code terminals (terminal.rc) and tasks (BASH_ENV). Change modules in Arc ▸ Modules,
# or by hand: module load …; module save ${c}
unset BASH_ENV   # tasks: load once, don't repeat in every child bash or leak into sbatch
type module >/dev/null 2>&1 || . /etc/profile.d/lmod.sh >/dev/null 2>&1 || true
type module >/dev/null 2>&1 && module --quiet restore ${c} >/dev/null 2>&1
true
`;
}

const TERMINAL_RC = `# Managed by the Arc HPC VS Code extension: VS Code terminals start \`bash --rcfile\` with this file.
[ -f ~/.bashrc ] && . ~/.bashrc
. ~/${MOD_DIR}/load.sh
`;

/** Diff of `env` before/after restoring the collection, as KEY=VALUE lines for python.envFile. */
function envScript(c: string) {
  return `d=~/${MOD_DIR}; b=$(mktemp); a=$(mktemp)
bash -c '. /etc/profile >/dev/null 2>&1; env -0' > "$b"
bash -c '. /etc/profile >/dev/null 2>&1; module --quiet restore ${c} >/dev/null 2>&1; env -0' > "$a"
{ echo "# Generated by the Arc HPC extension from Lmod collection \\"${c}\\" on $(date '+%F %T'). Regenerated on every change."
  echo "# Used via python.envFile (run/debug, tests, Jupyter kernels). Variables the collection unsets can't be expressed here."
  $(command -v gawk || echo awk) 'BEGIN { RS = "\\0" } NR == FNR { seen[$0] = 1; next }
    !($0 in seen) && index($0, "\\n") == 0 && $0 !~ /^(BASH_FUNC_|_=|SHLVL=|PWD=|OLDPWD=)/ { print }' "$b" "$a"
} > "$d/vscode.env.tmp" && mv "$d/vscode.env.tmp" "$d/vscode.env"
rm -f "$b" "$a"; `;
}

/** Write load.sh / terminal.rc (always — they're ours) and regenerate vscode.env. */
export async function writeModuleFiles(): Promise<void> {
  const c = collection();
  await runRemote(`mkdir -p ~/${MOD_DIR} && cat > ~/${MOD_DIR}/load.sh`, { stdin: loadSh(c) });
  await runRemote(`cat > ~/${MOD_DIR}/terminal.rc`, { stdin: TERMINAL_RC });
  await lmod(envScript(c)).catch(() => runRemote(`touch ~/${MOD_DIR}/vscode.env`));
}

// ─────────────── changing the collection ───────────────

/** Run `script` on top of the current collection, save it, refresh the files. Returns Lmod's messages. */
async function mutate(title: string, script: string): Promise<string | undefined> {
  if (!(await ensureSignedIn())) return;
  const c = collection();
  const out = await vscode.window.withProgress({ location: vscode.ProgressLocation.Notification, title: `Arc modules: ${title}…` }, () =>
    lmod(`${RESTORE(c)} out=$( { ${script}; } 2>&1 ); rc=$?; printf '%s\\n' "$out"; echo "@rc=$rc"; ` +
      `[ $rc -eq 0 ] && ! printf '%s' "$out" | grep -qiE ${q(LMOD_ERROR.source)} && module save ${q(c)} >/dev/null 2>&1 && echo "@saved"; exit 0`));
  const msg = lines(out).filter(l => !l.startsWith('@')).join('\n');
  if (!out.includes('@saved')) {
    const a = await vscode.window.showErrorMessage(`Arc modules: ${title} failed — the collection is unchanged.`, { detail: msg, modal: true }, 'Show output');
    if (a) await showReport(`module: ${title}`, msg || '(no output)', 'module-error');
    return;
  }
  await writeModuleFiles();
  modulesView?.refresh();
  if (msg) vscode.window.showInformationMessage(`Arc modules: ${msg.split('\n').slice(0, 3).join(' ')}`);
  else vscode.window.setStatusBarMessage(`Arc modules: ${title} — saved to "${c}". New terminals pick it up.`, 6000);
  return msg;
}

const modArg = (a: unknown) => (a as { data?: string } | undefined)?.data;

interface ModPick extends vscode.QuickPickItem { mod?: string; search?: boolean; }

export async function addModule() {
  if (!(await ensureSignedIn())) return;
  const c = collection();
  const raw = await vscode.window.withProgress({ location: vscode.ProgressLocation.Window, title: 'Arc: module avail' },
    () => lmod(`${RESTORE(c)} module -t avail 2>&1`));
  const loaded = new Set((await getState()).loaded);
  const items: ModPick[] = [];
  for (const l of lines(raw)) {
    if (l.endsWith(':')) { items.push({ label: l.slice(0, -1), kind: vscode.QuickPickItemKind.Separator }); continue; }
    const m = clean(l);
    if (m.endsWith('/') || (!m.includes('/') && raw.includes(`${m}/`))) continue;  // family lines when versions follow
    const isDefault = /\((?:default|D)\)/.test(l);
    items.push({ label: m, description: [isDefault ? 'default' : '', loaded.has(m) ? '✓ loaded' : ''].filter(Boolean).join(' · '), mod: m });
  }
  items.push({ label: '', kind: vscode.QuickPickItemKind.Separator },
    { label: '$(search) Not listed? Search every installed module (module spider)…', search: true, alwaysShow: true });
  const pick = await vscode.window.showQuickPick(items, {
    title: `Add a module to "${c}"`, placeHolder: 'Shows what is loadable with your current modules (module avail). Type to filter.',
    matchOnDescription: true,
  });
  if (!pick) return;
  if (pick.search) return searchModules();
  if (pick.mod) await mutate(`load ${pick.mod}`, `module load ${q(pick.mod)}`);
}

/** module spider: find modules hidden behind a compiler/MPI hierarchy, and load their prerequisites too. */
export async function searchModules() {
  if (!(await ensureSignedIn())) return;
  const term = await vscode.window.showInputBox({ title: 'Search all installed modules (module spider)', placeHolder: 'e.g. cuda, R, python, gromacs' });
  if (!term) return;
  const all = lines(await lmod(`module -t spider 2>&1 | grep -i -- ${q(term)} || true`)).map(clean).filter(m => !m.endsWith(':'));
  if (!all.length) { vscode.window.showInformationMessage(`No module matches "${term}".`); return; }
  const mod = await vscode.window.showQuickPick(all, { title: `module spider ${term}`, placeHolder: 'Pick a module to see how to load it' });
  if (!mod) return;
  const info = await lmod(`module spider ${q(mod)} 2>&1`);
  await showReport(`module spider ${mod}`, info, `spider-${mod}`);
  const prereqs = parsePrereqs(info);
  const options = prereqs.length
    ? prereqs.map(p => ({ label: `$(add) Load ${p} first, then ${mod}`, script: `module load ${p.split(/\s+/).map(q).join(' ')} ${q(mod)}` }))
    : [{ label: `$(add) Add ${mod}`, script: `module load ${q(mod)}` }];
  const go = await vscode.window.showQuickPick(options, { title: `Add ${mod} to "${collection()}"` });
  if (go) await mutate(`load ${mod}`, go.script);
}

/** Lines under "You will need to load all module(s) on any one of the lines below…". */
export function parsePrereqs(spider: string): string[] {
  const i = spider.search(/on any one of the lines below/i);
  if (i < 0) return [];
  const out: string[] = [];
  for (const l of spider.slice(i).split('\n').slice(1)) {
    const t = l.trim();
    if (!t) { if (out.length) break; continue; }
    if (/^(Help|Description|Additional|This module)/i.test(t)) break;
    out.push(t.replace(/\s+/g, ' '));
  }
  return out;
}

export async function unloadModule(arg?: unknown) {
  const m = modArg(arg) ?? await pickLoaded('Unload which module?');
  if (m) await mutate(`unload ${m}`, `module unload ${q(m)}`);
}

export async function swapModule(arg?: unknown) {
  const m = modArg(arg) ?? await pickLoaded('Change the version of which module?');
  if (!m) return;
  const name = m.includes('/') ? m.slice(0, m.lastIndexOf('/')) : m;
  const versions = lines(await lmod(`${RESTORE(collection())} module -t avail ${q(name)} 2>&1; module -t spider ${q(name)} 2>&1`))
    .map(clean).filter(v => v.startsWith(`${name}/`) && v !== m);
  const uniq = [...new Set(versions)];
  if (!uniq.length) { vscode.window.showInformationMessage(`No other versions of ${name} are installed.`); return; }
  const v = await vscode.window.showQuickPick(uniq, { title: `module swap ${m} → …` });
  if (v) await mutate(`swap ${m} → ${v}`, `module swap ${q(m)} ${q(v)}`);
}

export async function moduleHelp(arg?: unknown) {
  const m = modArg(arg) ?? await pickLoaded('Show help for which module?');
  if (!m) return;
  await showReport(`module help ${m}`, await lmod(`module help ${q(m)} 2>&1; echo; module whatis ${q(m)} 2>&1; echo; module spider ${q(m)} 2>&1`), `help-${m}`);
}

export async function resetModules() {
  const c = collection();
  const ok = await vscode.window.showWarningMessage(`Reset "${c}" to Arc's default modules?`,
    { modal: true, detail: 'Runs module reset (or module restore system) and saves the result.' }, 'Reset');
  if (ok) await mutate('reset to defaults', 'module reset 2>/dev/null || { module purge && module restore system; }');
}

async function pickLoaded(title: string): Promise<string | undefined> {
  if (!(await ensureSignedIn())) return;
  const s = await getState();
  if (!s.loaded.length) { vscode.window.showInformationMessage('No modules loaded.'); return; }
  return vscode.window.showQuickPick(s.loaded, { title });
}

/** A terminal with the collection loaded, from any window (local windows go through ssh). */
export async function moduleTerminal() {
  if (!(await ensureSignedIn())) return;
  if (onArc()) {
    const t = vscode.window.createTerminal({ name: `Arc modules (${collection()})`, shellPath: 'bash',
      shellArgs: ['--rcfile', `/home/${utsaId()}/${MOD_DIR}/terminal.rc`], iconPath: new vscode.ThemeIcon('package') });
    t.show();
  } else {
    arcTerminal(`Arc modules (${collection()})`, `. ~/${MOD_DIR}/load.sh; module list; exec bash -i`);
  }
}

/** Put the module set into a batch script: `module restore` or explicit, reproducible load lines. */
export async function insertIntoScript() {
  const ed = vscode.window.activeTextEditor;
  if (!ed) { vscode.window.showInformationMessage('Open a batch script (.sbatch / .slurm / .sh) first.'); return; }
  if (!(await ensureSignedIn())) return;
  const c = collection();
  const { loaded } = await getState();
  const pick = await vscode.window.showQuickPick([
    { label: '$(list-ordered) Explicit module load lines', detail: `Reproducible: the job keeps these versions even if you change "${c}" later. Best for results you'll rerun or share.`, v: 'explicit' },
    { label: `$(sync) module restore ${c}`, detail: 'Follows your VS Code set: whatever the collection holds when the job starts.', v: 'restore' },
  ], { title: 'Insert modules into this script' });
  if (!pick) return;
  const text = pick.v === 'restore'
    ? `module purge\nmodule restore ${c}        # same modules as your VS Code terminals (Arc ▸ Modules)\n`
    : `module purge\n${loaded.map(m => `module load ${m}`).join('\n')}\nmodule list\n`;
  const doc = ed.document;
  let line = -1;
  for (let i = 0; i < doc.lineCount; i++) if (/^#SBATCH/.test(doc.lineAt(i).text)) line = i;
  const at = line >= 0 ? new vscode.Position(line + 1, 0) : ed.selection.active;
  await ed.edit(e => e.insert(at, `${line >= 0 ? '\n' : ''}# Modules — ${DOCS}\n${text}`));
}

// ─────────────── view ───────────────

let modulesView: { refresh(): void } | undefined;
export const setModulesView = (v: { refresh(): void }) => { modulesView = v; };

/** Does this Arc workspace route terminals / Python through the module files? */
function appliedHere(): boolean | undefined {
  if (!onArc()) return undefined;
  const t = vscode.workspace.getConfiguration('terminal.integrated').get<string>('defaultProfile.linux');
  const p = vscode.workspace.getConfiguration('python').get<string>('envFile') ?? '';
  return t === TERMINAL_PROFILE && p.endsWith(`${MOD_DIR}/vscode.env`);
}

export async function moduleItems(): Promise<Item[]> {
  const c = collection();
  const s = await getState();
  const head = new Item(`collection "${c}"`, {
    icon: s.saved ? 'package' : 'circle-large-outline',
    description: s.saved ? `${s.loaded.length} module${s.loaded.length === 1 ? '' : 's'}` : 'not saved yet · showing Arc defaults',
    tooltip: new vscode.MarkdownString(
      `**Lmod collection \`${c}\`**${s.saved ? '' : ' (not saved yet: add or change a module to create it)'}\n\n` +
      `Used by:\n- new VS Code terminals and tasks\n- Python run/debug, tests and Jupyter kernels (\`python.envFile\`)\n` +
      `- batch scripts that run \`module restore ${c}\` (**Insert Modules into Script**)\n\n[Arc docs: module environments](${DOCS})`),
    context: 'modules:head',
  });
  const items = [head, ...s.loaded.map(m => {
    const i = m.lastIndexOf('/');
    return new Item(i > 0 ? m.slice(0, i) : m, {
      description: i > 0 ? m.slice(i + 1) : '', icon: 'symbol-package', context: 'module', data: m,
      tooltip: `${m}\nClick for module help · change version · unload`,
      command: { command: 'arc.modules.help', title: 'Help', arguments: [{ data: m }] },
    });
  })];
  if (appliedHere() === false) {
    items.push(new Item('Not applied to this workspace\'s terminals/Python', {
      icon: 'warning', color: 'charts.yellow', description: 'Review settings…',
      tooltip: 'The Arc workspace template (v3) sets the terminal profile, task shell and python.envFile. Review merges it without overwriting your edits.',
      command: { command: 'arc.reviewWorkspaceSettings', title: 'Review' },
    }));
  }
  return items;
}
